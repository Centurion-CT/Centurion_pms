<?php

declare(strict_types=1);

use App\Livewire\Dashboard\Rooms\MediaManager;
use App\Models\Media;
use App\Models\Operator;
use App\Models\Property;
use App\Models\Room;
use App\Models\Tenant;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Livewire\Livewire;

beforeEach(function (): void {
    config()->set('filesystems.default', 'public');
    config()->set('media-library.disk_name', 'public');
    Storage::fake('public');

    $this->tenant = Tenant::factory()->create(['slug' => 'media-test']);
    $this->tenant->makeCurrent();
    $this->property = Property::factory()->for($this->tenant)->create();
    $this->operator = Operator::factory()->for($this->tenant)->create();
    $this->room = Room::factory()->for($this->tenant)->for($this->property)->create();
});

afterEach(function (): void {
    Tenant::forgetCurrent();
});

/* --------------------------------------------------------------------------
 *  Upload + validation
 * ------------------------------------------------------------------------ */

it('uploads a JPG and creates a media row with conversions', function (): void {
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [UploadedFile::fake()->image('one.jpg', 600, 400)])
        ->call('upload')
        ->assertHasNoErrors();

    expect($this->room->getMedia('gallery'))->toHaveCount(1);

    $media = $this->room->getFirstMedia('gallery');
    expect($media->collection_name)->toBe('gallery');
    expect($media->mime_type)->toBe('image/jpeg');
    // Conversions are dispatched on the configured queue; QUEUE_CONNECTION=sync
    // so they should be generated by the time we get here.
    expect($media->hasGeneratedConversion('thumb'))->toBeTrue();
    expect($media->hasGeneratedConversion('medium'))->toBeTrue();
    expect($media->hasGeneratedConversion('full'))->toBeTrue();
});

it('uploads PNG + WebP', function (): void {
    Livewire::actingAs($this->operator, 'web')
