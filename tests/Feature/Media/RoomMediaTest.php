it('cascade-deletes media when the room is hard-deleted', function (): void {
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [UploadedFile::fake()->image('a.jpg', 100, 100)])
        ->call('upload');

    $mediaId = $this->room->getFirstMedia('gallery')->id;
    $this->room->forceDelete();

    expect(Media::find($mediaId))->toBeNull();
});

it('caps gallery at 20 images per room (PRD §6.3.3)', function (): void {
    // Pre-create 18 media rows via mediaCollection.onlyKeepLatest doesn't
    // help here — that hook only kicks in once we exceed during a single
    // batch. Instead, attach 18 first, then try a batch of 5 (only 2 should
    // land).
    $component = Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room]);

    for ($i = 0; $i < 18; $i++) {
        $component->set('photos', [UploadedFile::fake()->image("p{$i}.jpg", 100, 100)])
            ->call('upload');
    }
    expect($this->room->refresh()->getMedia('gallery'))->toHaveCount(18);

    $component->set('photos', [
        UploadedFile::fake()->image('a.jpg', 100, 100),
        UploadedFile::fake()->image('b.jpg', 100, 100),
        UploadedFile::fake()->image('c.jpg', 100, 100),
        UploadedFile::fake()->image('d.jpg', 100, 100),
        UploadedFile::fake()->image('e.jpg', 100, 100),
    ])->call('upload');

    expect($this->room->refresh()->getMedia('gallery'))->toHaveCount(20);
});
