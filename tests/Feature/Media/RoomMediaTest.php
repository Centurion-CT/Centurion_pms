it('persists drag-reorder via setNewOrder', function (): void {
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [
            UploadedFile::fake()->image('a.jpg', 100, 100),
            UploadedFile::fake()->image('b.jpg', 100, 100),
            UploadedFile::fake()->image('c.jpg', 100, 100),
        ])
        ->call('upload');

    $ids = $this->room->getMedia('gallery')->pluck('id')->all();
    $reversed = array_reverse($ids);

    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->call('reorder', $reversed);

    expect($this->room->refresh()->getMedia('gallery')->pluck('id')->all())->toBe($reversed);
});

it('reorder ignores media ids that do not belong to the room', function (): void {
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [UploadedFile::fake()->image('mine.jpg', 100, 100)])
        ->call('upload');

    $myId = $this->room->getFirstMedia('gallery')->id;

    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->call('reorder', [999_999, $myId, 888_888]); // poisoned input

    // My single row's order is unaffected; no exception.
    expect($this->room->refresh()->getMedia('gallery'))->toHaveCount(1);
});

it('deletes a single photo via the delete action', function (): void {
