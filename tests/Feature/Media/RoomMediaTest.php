it('stores media under tenant_{id}/ on the configured disk', function (): void {
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [UploadedFile::fake()->image('iso.jpg', 100, 100)])
        ->call('upload');

    $media = $this->room->getFirstMedia('gallery');
    $expectedPrefix = "tenant_{$this->tenant->id}/{$media->id}/";

    expect(Storage::disk('public')->exists($expectedPrefix.$media->file_name))->toBeTrue();
});

it('stamps tenant_id on the media row automatically', function (): void {
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [UploadedFile::fake()->image('iso.jpg', 100, 100)])
        ->call('upload');

    $media = $this->room->getFirstMedia('gallery');
    expect($media->tenant_id)->toBe($this->tenant->id);
});

it('404s when an operator tries to manage media for a foreign tenant\'s room', function (): void {
    $other = Tenant::factory()->create(['slug' => 'other-media']);
    $otherProp = Property::factory()->for($other)->create();
    Tenant::forgetCurrent();
    $other->makeCurrent();
    $foreignRoom = Room::factory()->for($other)->for($otherProp)->create();
    Tenant::forgetCurrent();
    $this->tenant->makeCurrent();

    $response = $this->actingAs($this->operator, 'web')
        ->get('http://media-test.keverna.test/dashboard/rooms/'.$foreignRoom->id.'/photos');

    $response->assertNotFound();
});

/* --------------------------------------------------------------------------
 *  Hero, alt text, reorder, delete, cascade
 * ------------------------------------------------------------------------ */

it('flags exactly one image as hero at a time', function (): void {
    $component = Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [
            UploadedFile::fake()->image('a.jpg', 100, 100),
            UploadedFile::fake()->image('b.jpg', 100, 100),
        ])
        ->call('upload');

    $ids = $this->room->getMedia('gallery')->pluck('id')->all();

    $component->call('setHero', $ids[0]);
    $component->call('setHero', $ids[1]);

    $heroes = $this->room->refresh()->getMedia('gallery')
        ->filter(fn ($m) => (bool) $m->getCustomProperty('is_hero'));
    expect($heroes)->toHaveCount(1);
    expect($heroes->first()->id)->toBe($ids[1]);
});

it('heroImage() returns the flagged hero, falling back to the first photo', function (): void {
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $this->room])
        ->set('photos', [
            UploadedFile::fake()->image('a.jpg', 100, 100),
            UploadedFile::fake()->image('b.jpg', 100, 100),
        ])
        ->call('upload');

    $room = $this->room->refresh();
    expect($room->heroImage())->not->toBeNull();
    expect($room->heroImage()->id)->toBe($room->getMedia('gallery')->first()->id);

    $second = $room->getMedia('gallery')->skip(1)->first();
    Livewire::actingAs($this->operator, 'web')
        ->test(MediaManager::class, ['room' => $room])
        ->call('setHero', $second->id);

    expect($room->refresh()->heroImage()->id)->toBe($second->id);
});

it('saves alt text on a media row', function (): void {
    Livewire::actingAs($this->operator, 'web')
