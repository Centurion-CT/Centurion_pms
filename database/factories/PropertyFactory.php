<?php

declare(strict_types=1);

namespace Database\Factories;

use App\Enums\PropertyType;
use App\Models\Property;
use App\Models\Tenant;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<Property>
 */
class PropertyFactory extends Factory
{
    protected $model = Property::class;

    /**
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'tenant_id' => Tenant::factory(),
            'name' => $this->faker->company().' Property',
            'type' => $this->faker->randomElement(PropertyType::cases()),
            'description' => $this->faker->paragraph(),
            'address' => $this->faker->streetAddress(),
            'city' => 'Lagos',
            'state' => 'Lagos',
            'is_live' => false,
            // Solo-fork default (opt-in): factory rows start off the
            // marketplace, matching what SeedInstallation writes. Tests
            // that need the marketplace stays layout should opt in
            // explicitly via ->create(['is_listed_publicly' => true]).
            // public_slug is auto-generated by Property::booted().
            'is_listed_publicly' => false,
            'amenities' => null,
            // Branding defaults added in §10 — explicit so factory-built rows
            // hydrate fully without a fresh() roundtrip.
            'primary_color' => '#1f6feb',
            'tagline' => null,
            'font_theme' => 'inter_playfair',
            'section_visibility' => null,
            'whatsapp_button_enabled' => false,
            'whatsapp_button_prefill' => null,
        ];
    }

    public function live(): self
    {
        return $this->state(fn () => ['is_live' => true]);
    }
}
