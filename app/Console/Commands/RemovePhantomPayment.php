<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Enums\PaymentStatus;
use App\Models\Booking;
use App\Models\Payment;
use App\Multitenancy\TenantScope;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

/**
 * Ops one-shot for the pre-24b5a5d prod bug where the manual-create
 * form defaulted payment_settlement='succeeded' and auto-recorded a
 * phantom cash Payment matching the booking's total_amount. This
 * command deletes that phantom row + restores the outstanding
 * balance, wrapped in a transaction + gated behind --force.
 *
 * Usage:
 *   php artisan bookings:remove-phantom-payment KV-UEE4BQWU
 *     → dry-run: prints the candidate rows without touching anything
 *   php artisan bookings:remove-phantom-payment KV-UEE4BQWU --force
 *     → deletes the phantom + rebalances the booking
 */
class RemovePhantomPayment extends Command
{
    protected $signature = 'bookings:remove-phantom-payment
                            {ref : Booking reference (e.g. KV-UEE4BQWU)}
                            {--force : Actually delete + rebalance (default is dry-run)}
                            {--method=cash : Payment method to match against (default: cash)}';

    protected $description = 'Delete a phantom cash payment autogenerated by the pre-24b5a5d manual-create default';

    public function handle(): int
    {
        $ref = (string) $this->argument('ref');
        $method = (string) $this->option('method');
        $isDry = ! $this->option('force');

        // Bypass TenantScope so this works from an artisan context
        // that hasn't bound a current tenant.
        $booking = Booking::query()
            ->withoutGlobalScope(TenantScope::class)
            ->where('booking_ref', $ref)
            ->first();

        if ($booking === null) {
            $this->error("No booking with ref {$ref}.");
            return self::FAILURE;
        }

        $this->info("Booking #{$booking->id}");
        $this->line("  Ref:         {$booking->booking_ref}");
        $this->line("  Guest:       {$booking->guest_name}");
        $this->line("  Total:       ₦".number_format((int) $booking->total_amount));
        $this->line("  Deposit:     ₦".number_format((int) $booking->deposit_amount));
        $this->line("  Balance due: ₦".number_format((int) $booking->balance_due));
        $this->line("  Status:      {$booking->booking_status->value} · {$booking->payment_status->value}");
        $this->newLine();

        // Diagnostic: list EVERY Payment row so the operator can
        // eyeball the ledger + we can spot fingerprint mismatches.
        $allPayments = Payment::query()
            ->where('booking_id', $booking->id)
            ->orderBy('id')
            ->get();

        $this->info('Payments ledger on this booking ('.$allPayments->count().' row(s)):');
        if ($allPayments->isEmpty()) {
            $this->line('  (none)');
        }
        foreach ($allPayments as $p) {
            $this->line(sprintf(
                '  Payment #%d  %s  ₦%s  status=%s  paid_at=%s',
                $p->id,
                $p->method ?? '—',
                number_format((int) ($p->amount ?? 0)),
                (string) ($p->status?->value ?? $p->status ?? '—'),
                (string) ($p->paid_at ?? $p->created_at ?? '—'),
            ));
        }
        $this->newLine();

        // Fingerprint match: method + amount === total_amount.
        $totalNgn = (int) $booking->total_amount;
        $candidates = $allPayments->filter(function ($p) use ($method, $totalNgn) {
            $rowMethod = $p->method;
            $rowAmount = (int) ($p->amount ?? 0);
            return $rowMethod !== null
                && mb_strtolower((string) $rowMethod) === mb_strtolower($method)
                && $rowAmount === $totalNgn;
        })->values();

        // Ledger reality check: what has the booking ACTUALLY collected?
        $succeededSum = (int) $allPayments
            ->filter(fn ($p) => $p->status?->value === PaymentStatus::Succeeded->value)
            ->sum('amount');
        $expectedBalance = max(0, $totalNgn - (int) $booking->deposit_amount - $succeededSum);
        $currentBalance = (int) $booking->balance_due;

        $this->info('Reconciliation:');
        $this->line("  Total - Deposit - Succeeded payments = ₦".number_format($expectedBalance)." (expected balance)");
        $this->line("  Current balance_due on the booking   = ₦".number_format($currentBalance));
        $balanceMismatch = $expectedBalance !== $currentBalance;
        if ($balanceMismatch) {
            $this->warn("  ⚠ Mismatch — the balance was zeroed WITHOUT a real Payment row.");
        }
        $this->newLine();

        if ($candidates->count() > 1) {
            $this->warn('More than one fingerprint-matching candidate — bailing to avoid deleting a real payment. Investigate manually.');
            return self::FAILURE;
        }

        // Nothing to do — no phantom to delete AND balance is already correct.
        if ($candidates->isEmpty() && ! $balanceMismatch) {
            $this->comment('No phantom payment and no balance mismatch. Nothing to fix.');
            return self::SUCCESS;
        }

        if ($isDry) {
            $planned = [];
            if ($candidates->count() === 1) {
                $planned[] = "delete Payment #{$candidates->first()->id}";
            }
            if ($balanceMismatch) {
                $planned[] = "reset balance_due ₦".number_format($currentBalance)." → ₦".number_format($expectedBalance).", flip payment_status to Pending";
            }
            $this->comment('DRY-RUN — would '.implode(' + ', $planned).'. Re-run with --force to apply.');
            return self::SUCCESS;
        }

        $deletedCount = 0;

        DB::transaction(function () use ($booking, $candidates, $expectedBalance, &$deletedCount): void {
            if ($candidates->isNotEmpty()) {
                $deletedCount = Payment::query()
                    ->whereIn('id', $candidates->pluck('id')->all())
                    ->delete();
            }

            $booking->forceFill([
                'balance_due'    => $expectedBalance,
                'payment_status' => $expectedBalance > 0 ? PaymentStatus::Pending : PaymentStatus::Succeeded,
            ])->save();

            activity('booking')
                ->performedOn($booking->refresh())
                ->event('phantom_payment_removed')
                ->withProperties([
                    'deleted_payment_ids' => $candidates->pluck('id')->all(),
                    'restored_balance'    => $expectedBalance,
                    'reason'              => 'pre-24b5a5d manual-create default; balance rebalanced against actual ledger',
                ])
                ->log("Rebalanced {$booking->booking_ref}: deleted {$deletedCount} payment(s), balance_due→₦".number_format($expectedBalance));
        });

        $this->info("Done. Deleted {$deletedCount} payment(s). New balance_due=₦".number_format($expectedBalance));
        return self::SUCCESS;
    }
}
